def glossary_js():
    source = Path(__file__).with_name('ui_glossary.js').read_text(encoding='utf-8')
    return source.replace('__GLOSSARY_DATA__', json.dumps(TERMS, ensure_ascii=True))


def help_heading(title, term):
    from html import escape
    return f'<div class="term-section"><span>{escape(title)}</span><button type="button" class="term-help" data-terms="{escape(term, quote=True)}" aria-label="解释：{escape(term, quote=True)}" aria-expanded="false"></button></div>'


def chart_explanation(label):
    from html import escape
    term = next((term for term in sorted(TERMS, key=len, reverse=True) if term in label), None)
    if not term:
        return ''
    text = TERMS[term]
    return '<br>' + '<br>'.join(escape(text[i:i + 22]) for i in range(0, len(text), 22))


def search_glossary(query=''):
    from html import escape
    query = (query or '').strip().casefold()
    defaults = ['主营构成', '财报利润桥', '毛利', '归母净利润', '经营情景', '同口径']
    matches = [term for term, definition in TERMS.items()
               if query in term.casefold() or query in definition.casefold()] if query else defaults
    if query:
        matches.sort(key=lambda term: (term.casefold() != query, query not in term.casefold(), term))
    if not matches:
        return '<p class="glossary-status">没有匹配的术语。</p>'
    status = f'找到 {len(matches)} 个术语' if query else '常用术语'
    rows = ''.join(f'<div class="glossary-entry"><dt>{escape(term)}</dt><dd>{escape(TERMS[term])}</dd></div>'
                   for term in matches)
    return f'<p class="glossary-status">{status}</p><dl class="glossary-results">{rows}</dl>'
